/** Ordnet ein Lebensmittel anhand von Stichworten einem Gang im Laden zu. */
export function classifyAisle(name: string): Aisle {
  const n = ` ${name.toLowerCase()} `;
  for (const [aisle, words] of KEYWORDS) {
    if (words.some((w) => n.includes(w))) return aisle;
  }
  return 'other';
}

export function aisleLabel(aisle: string, locale: Locale = 'de') {
  return (AISLE_LABELS as Record<string, Record<Locale, string>>)[aisle]?.[locale] ?? aisle;
}
